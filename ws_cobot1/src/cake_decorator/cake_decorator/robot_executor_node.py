"""작업 요청을 실제 로봇 동작으로 연결할 노드의 자리. 아직 구현하지 않는다."""

# 예정 역할: DrawOnCake ActionServer로 경로 실행 요청을 받는다.
# PickAndPlace·GraspTool ActionServer는 운반·펜 자동 파지 개발 시 구현한다.
# 경로·속도·로봇 준비 상태를 검사한 뒤 drawing_motion.py의 동작 함수를 호출한다.
# 진행 상태를 Feedback으로 보내고 실제 실행 결과로 Result를 구성한다.
# 장비를 동시에 조작하는 요청이 겹치지 않도록 실행을 직렬화해야 한다.
# 긴 DRL 호출 중에도 상태·취소 요청을 처리할 실행 구조가 필요하다.
# 취소 접수만으로 실제 정지를 단정하거나 무조건 홈으로 복귀하지 않는다.
# 설정에 따른 virtual/real 대상 확인은 실제 장비 연결을 구현할 때 추가한다.
